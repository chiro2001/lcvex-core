def validate_rows(rows):
    errors = []
    seen = set()
    for i, r in enumerate(rows):
        rid = r.get("row_id", f"<missing@{i}>")
        for field in sorted(REQUIRED_FIELDS):
            if field not in r:
                errors.append(f"{rid}: missing required field {field}")
        if r.get("category") not in CATEGORIES:
            errors.append(f"{rid}: invalid category {r.get('category')!r}")
        if r.get("status") not in STATUSES:
            errors.append(f"{rid}: invalid status {r.get('status')!r}")
        if r.get("required") not in (True, False):
            errors.append(f"{rid}: required must be boolean")
        if rid in seen:
            errors.append(f"{rid}: duplicate row_id")
        seen.add(rid)
        if not r.get("qemu_oracle", "").strip():
            errors.append(f"{rid}: qemu_oracle is empty; must have oracle or explicit blocked/deferred reason")
        if r.get("status") in ("blocked", "deferred") and not r.get("notes", "").strip():
            errors.append(f"{rid}: blocked/deferred row must have explicit notes/reason")
        if not r.get("encoding", "").strip():
            errors.append(f"{rid}: encoding is empty")
        if not r.get("arch_version", "").strip():
            errors.append(f"{rid}: arch_version is empty")
        if not r.get("rtl", "").strip():
            errors.append(f"{rid}: rtl location is empty")
    return errors


def summarize(rows):
    stats = {"total": len(rows)}
    for cat in sorted(CATEGORIES):
        stats[cat] = sum(1 for r in rows if r["category"] == cat)
    for st in sorted(STATUSES):
        stats[st] = sum(1 for r in rows if r["status"] == st)
    stats["implemented"] = sum(1 for r in rows if r["status"] == "implemented")
    stats["blocked_or_deferred"] = sum(
        1 for r in rows if r["status"] in ("blocked", "deferred"))
    return stats


