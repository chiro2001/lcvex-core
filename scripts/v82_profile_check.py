def extract_manifest_json(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.search(r"<!-- V82_PROFILE_DATA_START -->\s*```json\s*(.*?)\s*```\s*<!-- V82_PROFILE_DATA_END -->",
                  text, re.S)
    if not m:
        raise SystemExit(f"{path}: cannot find embedded JSON block")
    return json.loads(m.group(1))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--validate-manifest", action="store_true",
                    help="validate embedded JSON in docs/V82_PROFILE_MANIFEST.md")
    ap.add_argument("--emit-manifest", type=Path, default=None,
                    help="write/generate docs/V82_PROFILE_MANIFEST.md")
    ap.add_argument("--summary", action="store_true", help="print distribution")
    args = ap.parse_args(argv)

    if args.emit_manifest is not None:
        out = args.emit_manifest
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(manifest_text(ROWS, MANIFEST_META), encoding="utf-8")
        print(f"manifest written: {out}")
        return 0

    rows = ROWS
    errors = validate_rows(rows)
    if errors:
        for e in errors:
            print(f"ERROR: {e}", file=sys.stderr)
        return 1

    if args.validate_manifest:
        path = DEFAULT_MANIFEST if args.emit_manifest is None else args.emit_manifest
        if not path.exists():
            print(f"ERROR: manifest not found: {path}", file=sys.stderr)
            return 2
        data = extract_manifest_json(path)
        mrows = data.get("rows", [])
        mem_errors = validate_rows(mrows)
        if mem_errors:
            for e in mem_errors:
                print(f"ERROR(manifest): {e}", file=sys.stderr)
            return 1
        if mrows != ROWS:
            print("ERROR: manifest embedded rows differ from built-in ROWS", file=sys.stderr)
            return 1
        print(f"OK: manifest rows validated ({len(mrows)} rows)")

    if args.summary:
        stats = summarize(rows)
        for k in sorted(stats):
            print(f"{k}: {stats[k]}")

    if not args.validate_manifest and not args.summary:
        print(f"OK: built-in ROWS validated ({len(rows)} rows)")
        if errors:
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
